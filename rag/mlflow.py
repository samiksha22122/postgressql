# MAGIC #02. Setting up configs for Notebook
# MAGIC

# COMMAND ----------

dbcEnv = os.getenv("dbc_environment")

# COMMAND ----------

serving_config = {
    "model_name": "question-answering",
    "catalog_settings": {"catalog": f"commercial_{dbcEnv}", "schema": "medical_affair_core"},
    "serving_endpoint_settings": {
        "endpoint_name": "question-answer",
        "workload_size": "Small",
        "scale_to_zero_enabled": True,
    },
}

# COMMAND ----------

mlflow.set_registry_uri("databricks-uc")

# COMMAND ----------

client = MlflowClient()

# COMMAND ----------

# MAGIC %md
# MAGIC #03. Register Model to Catalog

# COMMAND ----------

registry_details = mlflow.register_model(
    model_uri=f"runs:/{run_id}/{serving_config['model_name']}",
    name=f"{serving_config['catalog_settings']['catalog']}.{serving_config['catalog_settings']['schema']}.{serving_config['model_name']}"
)

# COMMAND ----------

# Set the model version alias to "Champion"
client.set_registered_model_alias(
    name=registry_details.name,
    version=registry_details.version,
    alias="Champion"
)

# COMMAND ----------

